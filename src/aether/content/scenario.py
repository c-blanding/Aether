from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

from aether.aether import Aether
from aether.components.shared import AetherValidationError
from aether.domain.world import World


class ScenarioLoadError(AetherValidationError):
    """Raised when a scenario file cannot be loaded or applied."""


class ScenarioPersonality(BaseModel):
    traits: list[str] = Field(default_factory=list)
    values: list[str] = Field(default_factory=list)
    fears: list[str] = Field(default_factory=list)
    speaking_style: str | None = None


class ScenarioGoal(BaseModel):
    description: str
    priority: int = 50


class ScenarioBelief(BaseModel):
    proposition: str
    believed_value: str = "true"
    confidence: float = 1.0


class ScenarioMemory(BaseModel):
    summary: str
    perspective: str | None = None
    importance: float = 0.5
    emotion: str | None = None


class ScenarioCharacter(BaseModel):
    id: str | None = None
    name: str
    role: str = ""
    background: str = ""
    location: str | None = None
    personality: ScenarioPersonality = Field(default_factory=ScenarioPersonality)
    goals: list[ScenarioGoal] = Field(default_factory=list)
    beliefs: list[ScenarioBelief] = Field(default_factory=list)
    memories: list[ScenarioMemory] = Field(default_factory=list)
    capabilities: list[str] = Field(default_factory=list)


class ScenarioItem(BaseModel):
    id: str | None = None
    name: str
    description: str = ""
    location: str | None = None
    owner: str | None = None
    hidden: bool = False
    tags: list[str] = Field(default_factory=list)


class ScenarioLocation(BaseModel):
    id: str | None = None
    name: str
    description: str = ""
    connections: list[str] = Field(default_factory=list)


class ScenarioDocument(BaseModel):
    name: str
    description: str = ""
    locations: list[ScenarioLocation] = Field(default_factory=list)
    characters: list[ScenarioCharacter] = Field(default_factory=list)
    items: list[ScenarioItem] = Field(default_factory=list)


def _read_document(path: Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    suffix = path.suffix.lower()
    if suffix == ".json":
        data = json.loads(text)
    elif suffix in {".yaml", ".yml"}:
        try:
            import yaml  # type: ignore
        except ImportError as exc:
            raise ScenarioLoadError(
                "PyYAML is required to load .yaml/.yml scenarios. "
                "Install pyyaml or use a .json scenario file."
            ) from exc
        data = yaml.safe_load(text)
    else:
        raise ScenarioLoadError(
            f"Unsupported scenario format '{path.suffix}'. Use .json, .yaml, or .yml."
        )

    if not isinstance(data, dict):
        raise ScenarioLoadError("Scenario root must be a mapping/object.")
    return data


def load_scenario(
    aether: Aether,
    path: str | Path,
) -> World:
    """
    Load a JSON/YAML scenario into a new world on the given SDK instance.

    Location/character/item ``id`` fields are authoring keys used inside the
    file for references (connections, location, owner). Runtime IDs are still
    generated by the domain models; references are resolved by those keys or
    by unique names when ids are omitted.
    """
    scenario_path = Path(path)
    if not scenario_path.is_file():
        raise ScenarioLoadError(f"Scenario file not found: {scenario_path}")

    document = ScenarioDocument.model_validate(_read_document(scenario_path))
    world = aether.create_world(
        name=document.name,
        description=document.description,
    )

    def _bind(mapping: dict[str, str], key: str, value: str, kind: str) -> None:
        existing = mapping.get(key)
        if existing is not None and existing != value:
            raise ScenarioLoadError(
                f"Duplicate {kind} key '{key}' maps to different entities."
            )
        mapping[key] = value

    locations_by_key: dict[str, str] = {}
    for entry in document.locations:
        location = world.create_location(
            name=entry.name,
            description=entry.description,
        )
        key = entry.id or entry.name
        _bind(locations_by_key, key, location.id, "location")
        _bind(locations_by_key, entry.name, location.id, "location")

    # Second pass for connections so forward references work.
    for entry in document.locations:
        from_key = entry.id or entry.name
        from_id = locations_by_key[from_key]
        for target_key in entry.connections:
            to_id = locations_by_key.get(target_key)
            if to_id is None:
                raise ScenarioLoadError(
                    f"Unknown connection target '{target_key}' "
                    f"from location '{from_key}'."
                )
            world.connect_locations(from_id, to_id, bidirectional=True)

    characters_by_key: dict[str, str] = {}
    for entry in document.characters:
        location_id = None
        if entry.location:
            location_id = locations_by_key.get(entry.location)
            if location_id is None:
                raise ScenarioLoadError(
                    f"Unknown location '{entry.location}' for character "
                    f"'{entry.name}'."
                )
        character = world.create_character(
            name=entry.name,
            role=entry.role,
            background=entry.background,
            location_id=location_id,
        )
        character.personality.traits = list(entry.personality.traits)
        character.personality.values = list(entry.personality.values)
        character.personality.fears = list(entry.personality.fears)
        character.personality.speaking_style = entry.personality.speaking_style
        for goal in entry.goals:
            character.add_goal(goal.description, priority=goal.priority)
        for belief in entry.beliefs:
            character.learn(
                belief.proposition,
                believed_value=belief.believed_value,
                confidence=belief.confidence,
            )
        for memory in entry.memories:
            character.remember(
                memory.summary,
                perspective=memory.perspective,
                importance=memory.importance,
                emotion=memory.emotion,
            )
        for capability in entry.capabilities:
            character.add_capability(capability)

        key = entry.id or entry.name
        _bind(characters_by_key, key, character.id, "character")
        _bind(characters_by_key, entry.name, character.id, "character")

    for entry in document.items:
        location_id = None
        owner_id = None
        if entry.location:
            location_id = locations_by_key.get(entry.location)
            if location_id is None:
                raise ScenarioLoadError(
                    f"Unknown location '{entry.location}' for item '{entry.name}'."
                )
        if entry.owner:
            owner_id = characters_by_key.get(entry.owner)
            if owner_id is None:
                raise ScenarioLoadError(
                    f"Unknown owner '{entry.owner}' for item '{entry.name}'."
                )
        world.create_item(
            name=entry.name,
            description=entry.description,
            location_id=location_id,
            owner_id=owner_id,
            hidden=entry.hidden,
            tags=entry.tags,
        )

    aether.save(world)
    return world
